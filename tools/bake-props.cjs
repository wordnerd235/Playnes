// Dev tool: bake the trees' and buildings' pictures (see tools/bake-props.html).
// Writes public/sprites/props.png (convert to WebP afterwards) and src/data/propSprites.ts.
// Usage: node tools/bake-props.cjs
const { chromium } = require("playwright");
const http = require("http");
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
(async () => {
  const server = http.createServer((req, res) => {
    const f = path.join(root, decodeURIComponent(req.url.split("?")[0]));
    fs.readFile(f, (err, data) => (err ? res.writeHead(404).end() : res.writeHead(200, { "content-type": f.endsWith(".html") ? "text/html" : f.endsWith(".js") ? "text/javascript" : "application/octet-stream" }).end(data)));
  });
  await new Promise((r) => server.listen(0, "127.0.0.1", r));
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
  page.on("pageerror", (e) => console.log("page error:", e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/tools/bake-props.html`);
  await page.waitForFunction(() => document.title === "ready", null, { timeout: 60000 });
  const { sheet, manifest } = await page.evaluate(() => ({ sheet: window.__sheet, manifest: window.__manifest }));
  fs.mkdirSync(path.join(root, "public/sprites"), { recursive: true });
  fs.writeFileSync(path.join(root, "public/sprites/props.png"), Buffer.from(sheet.split(",")[1], "base64"));
  fs.writeFileSync(
    path.join(root, "src/data/propSprites.ts"),
    `// Generated by tools/bake-props.cjs. Do not edit by hand.\n// One sheet of pictures: a row per kind of tree or building, a column per looking-down angle.\n// frames[i].size = the picture's side in metres; origin = where the thing stands in it.\nexport interface PropSprite {\n  row: number;\n  /** Height of the thing itself, and how far it reaches from its middle, metres. */\n  height: number;\n  radius: number;\n  frames: { size: number; origin: "bottom" | "centre" }[];\n}\n\nexport const PROP_SHEET = { file: "sprites/props.webp", cell: ${manifest.cell}, elevations: ${JSON.stringify(manifest.elevations)} };\n\nexport const PROP_SPRITES: Record<string, PropSprite> = ${JSON.stringify(manifest.types, null, 2)};\n`,
  );
  console.log("wrote public/sprites/props.png and src/data/propSprites.ts:", Object.keys(manifest.types).join(", "));
  await browser.close();
  server.close();
})();
