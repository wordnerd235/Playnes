// Dev tool: render every playne model to a transparent picture for the hangar tiles, plus a big
// side view of the Cessna (with tap spots) for the "Meet your playne" lesson.
// Usage: serve the repo root on :8765, then  node tools/render-planes.cjs
// Writes public/models/thumbs/<id>.png and src/data/meetSpots.ts; then convert to WebP:
//   python3 -c "from PIL import Image;import glob,os;[ (Image.open(f).convert('RGBA').save(f[:-4]+'.webp','WEBP',quality=82,method=6), os.remove(f)) for f in glob.glob('public/models/thumbs/*.png')]"
const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const ids = fs.readdirSync(path.join(root, "public/models")).filter((f) => f.endsWith(".glb") && !["ring.glb", "shadow.glb", "vaporcone.glb"].includes(f)).map((f) => f.replace(".glb", ""));
const outDir = path.join(root, "public/models/thumbs");
fs.mkdirSync(outDir, { recursive: true });

// Cessna 172 parts in model coordinates (metres; nose +Z, up +Y, left wing +X).
const MEET_POINTS = [
  { id: "wings", p: [-3.9, 2.25, 0.4] },
  { id: "tail", p: [0, 2.85, -3.4] },
  { id: "prop", p: [0, 1.55, 4.55] },
  { id: "wheels", p: [-1.25, 0.25, 0] },
  { id: "cockpit", p: [-0.45, 2.05, 2.75] },
];

(async () => {
  const browser = await chromium.launch();
  const shoot = async (id, view, w, h, points = []) => {
    const page = await browser.newPage({ viewport: { width: w, height: h } });
    const url = `http://127.0.0.1:8765/tools/render-plane.html?id=${id}&view=${view}&points=${encodeURIComponent(JSON.stringify(points))}`;
    await page.goto(url);
    await page.waitForFunction(() => document.title === "ready", null, { timeout: 60000 });
    const { png, pts } = await page.evaluate(() => ({ png: window.__png, pts: window.__points }));
    await page.close();
    return { buf: Buffer.from(png.split(",")[1], "base64"), pts };
  };
  for (const id of ids) {
    const { buf } = await shoot(id, "hero", 640, 400);
    fs.writeFileSync(path.join(outDir, `${id}.png`), buf);
    console.log("thumb", id);
  }
  const meet = await shoot("c172", "side", 1400, 760, MEET_POINTS);
  fs.writeFileSync(path.join(outDir, "meet-c172.png"), meet.buf);
  const spots = Object.fromEntries(meet.pts.map((p) => [p.id, { x: +p.x.toFixed(1), y: +p.y.toFixed(1) }]));
  fs.writeFileSync(
    path.join(root, "src/data/meetSpots.ts"),
    `// Generated by tools/render-planes.cjs: where each Cessna part is in public/models/thumbs/meet-c172 (percent).\nexport const MEET_SPOTS: Record<string, { x: number; y: number }> = ${JSON.stringify(spots, null, 2)};\n`,
  );
  console.log("meet spots", spots);
  await browser.close();
})();
